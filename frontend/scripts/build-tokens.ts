// Compile src/lib/themes/<theme>/tokens.json (W3C Design Tokens) into CSS custom properties.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const themesDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'themes');

type Group = { [key: string]: unknown };
export type Tokens = { light: Group; dark?: Group; shared?: Group };

function flatten(group: Group, prefix: string[] = []): [string, string][] {
  const out: [string, string][] = [];
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    if (node && typeof node === 'object' && '$value' in node) {
      out.push([[...prefix, key].join('-'), String(node.$value)]);
    } else if (node && typeof node === 'object') {
      out.push(...flatten(node as Group, [...prefix, key]));
    }
  }
  return out;
}

const declarations = (group: Group): string =>
  flatten(group)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n');

export function compileTheme(name: string, tokens: Tokens): string {
  const root = `:root[data-theme="${name}"]`;
  const parts = [`${root} {\n${declarations(tokens.light)}\n${declarations(tokens.shared ?? {})}\n}`];
  if (tokens.dark) {
    const dark = declarations(tokens.dark);
    parts.push(
      `@media (prefers-color-scheme: dark) {\n  ${root}:not([data-color-scheme="light"]) {\n${dark}\n  }\n}`,
      `${root}[data-color-scheme="dark"] {\n${dark}\n}`
    );
  }
  return parts.join('\n\n').replace(/\n\n\n/g, '\n');
}

export function buildAll(dir = themesDir) {
  const names = readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory());
  const css = names
    .map((e) => compileTheme(e.name, JSON.parse(readFileSync(join(dir, e.name, 'tokens.json'), 'utf8'))))
    .join('\n\n');
  writeFileSync(join(dir, 'themes.css'), `/* Generated by scripts/build-tokens.ts; do not edit. */\n${css}\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) buildAll();
