// The tokens and fonts of the pages the backend writes itself (sign-in, OIDC confirmation, recovery
// kit, /lite), compiled from the same sources as the SPA: `themes/bibliotheque/tokens.json` (the
// colours, light and dark), `themes/foundation.css` (the @font-face rules and everything that is
// not a colour). The backend serves the result as one stylesheet; `server-pages.test.ts` keeps
// the committed copy identical to what this script writes. Run it with `npm run pages:css`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const themes = join(here, '..', 'src', 'lib', 'themes');
export const TARGET = join(
  here,
  '..',
  '..',
  'backend',
  'src',
  'shelfhold',
  'interfaces',
  'http_api',
  'pages',
  'paper-ink.tokens.css'
);

type Group = { [key: string]: unknown };

function flatten(group: Group, prefix: string[] = []): [string, string][] {
  const out: [string, string][] = [];
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    if (node && typeof node === 'object' && '$value' in node) {
      out.push([[...prefix, key].join('-'), String(node.$value)]);
    } else if (node && typeof node === 'object') {
      out.push(...flatten(node as Group, [...prefix, key]));
    }
  }
  return out;
}

const lines = (group: Group, indent: string): string =>
  flatten(group)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n');

/** What the foundation holds that a server page needs: the font faces and the first `:root`. */
function fromFoundation(css: string): { faces: string; root: string; darkShadows: string } {
  const faces = css.match(/@font-face \{[^}]*\}/g);
  const root = css.match(/\n:root \{[\s\S]*?\n\}/);
  const dark = css.match(/@media \(prefers-color-scheme: dark\) \{\s*:root:not\(\[data-color-scheme='light'\]\) \{([\s\S]*?)\n {2}\}\n\}/);
  if (!faces || !root || !dark) throw new Error('foundation.css no longer has the shape this script reads');
  return { faces: faces.join('\n'), root: root[0].trim(), darkShadows: dark[1] ?? '' };
}

export function compileServerPages(): string {
  const tokens = JSON.parse(readFileSync(join(themes, 'bibliotheque', 'tokens.json'), 'utf8')) as {
    light: Group;
    dark: Group;
    shared: Group;
  };
  const { faces, root, darkShadows } = fromFoundation(readFileSync(join(themes, 'foundation.css'), 'utf8'));
  const dark = lines(tokens.dark, '    ');
  const darkForced = lines(tokens.dark, '  ');
  return [
    '/* Generated by frontend/scripts/build-server-pages.ts from the theme « Bibliothèque » and the',
    '   foundation of the SPA (npm run pages:css); do not edit. Fonts: frontend/static/fonts. */',
    faces,
    root,
    `:root {\n${lines(tokens.light, '  ')}\n${lines(tokens.shared, '  ')}\n}`,
    // the system choice, unless the page was told otherwise (appearance.js), then the forced dark
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-color-scheme='light']) {\n${dark}${darkShadows}\n  }\n}`,
    `:root[data-color-scheme='dark'] {\n${darkForced}${darkShadows.replace(/^ {4}/gm, '  ')}\n}`,
    ''
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(TARGET, compileServerPages());
