"""The stylesheet and the small scripts of the pages the server writes itself (sign-in, OIDC
confirmation, recovery kit, `/lite`).

Their CSP forbids inline code (`default-src 'none'`, nothing inline): a page links files that
this module serves from its own origin, so a tag that slipped into a page would run nothing and
paint nothing. The tokens and the font faces are the ones of the front, generated by
`frontend/scripts/build-server-pages.ts` into `pages/paper-ink.tokens.css` (a test keeps the copy
identical); the fonts themselves are the files of `frontend/static/fonts`, served by the front
under `/fonts/`: no second copy, no remote host.
"""

import hashlib
from functools import cache
from pathlib import Path

from fastapi import APIRouter, Request
from fastapi.responses import Response

__all__ = [
    "APPEARANCE_PATH",
    "CONFIRM_SCRIPT_PATH",
    "LOGIN_SCRIPT_PATH",
    "STYLE_PATH",
    "build_page_assets_router",
    "lite_style",
    "paper_ink_style",
    "serve_asset",
]

_PAGES = Path(__file__).parent / "pages"
STYLE_PATH = "/pages/paper-ink.css"
APPEARANCE_PATH = "/pages/appearance.js"
LOGIN_SCRIPT_PATH = "/pages/login.js"
CONFIRM_SCRIPT_PATH = "/pages/confirm.js"


@cache
def read_page_file(name: str) -> str:
    return (_PAGES / name).read_text("utf-8")


def paper_ink_style() -> str:
    """The tokens, then the base and the components of the server pages."""
    return read_page_file("paper-ink.tokens.css") + read_page_file("paper-ink.css")


def lite_style() -> str:
    """The same tokens (the fonts), then the black-and-white sheet of the e-readers."""
    return read_page_file("paper-ink.tokens.css") + read_page_file("lite.css")


def serve_asset(request: Request, body: str, media_type: str) -> Response:
    """A public file of the pages: no profile in it, so it may be kept, but always asked again
    (`no-cache` with an `ETag`): a new version of the server shows its new look at once."""
    etag = '"' + hashlib.sha256(body.encode()).hexdigest()[:32] + '"'
    headers = {"ETag": etag, "Cache-Control": "no-cache", "X-Content-Type-Options": "nosniff"}
    if request.headers.get("if-none-match") == etag:
        return Response(status_code=304, headers=headers)
    return Response(body, media_type=media_type, headers=headers)


def build_page_assets_router() -> APIRouter:
    router = APIRouter()

    @router.get(STYLE_PATH, include_in_schema=False)
    def style(request: Request) -> Response:
        return serve_asset(request, paper_ink_style(), "text/css")

    @router.get(APPEARANCE_PATH, include_in_schema=False)
    def appearance(request: Request) -> Response:
        return serve_asset(request, read_page_file("appearance.js"), "text/javascript")

    @router.get(LOGIN_SCRIPT_PATH, include_in_schema=False)
    def login_script(request: Request) -> Response:
        return serve_asset(request, read_page_file("login.js"), "text/javascript")

    @router.get(CONFIRM_SCRIPT_PATH, include_in_schema=False)
    def confirm_script(request: Request) -> Response:
        return serve_asset(request, read_page_file("confirm.js"), "text/javascript")

    return router
