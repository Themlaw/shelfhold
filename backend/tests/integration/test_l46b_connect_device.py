@pytest.mark.req("ENF-SEC-010")
def test_a_member_cannot_pair_a_reader_for_someone_else(world: World) -> None:
    """The refusal is the same for a profile that exists and one that does not (no probing)."""
    other = world.create(world.mum, "dad")
    ghost = world.send(world.mum, "POST", TOKENS, {"subject_user_id": "01HZZZZZZZZZZZZZZZZZZZZZZZ"})
    assert other.status_code == ghost.status_code == 403
    assert other.json()["code"] == ghost.json()["code"]
    assert db_rows(world.env.settings, "SELECT COUNT(*) FROM device_token")[0][0] == 0


@pytest.mark.req("ENF-SEC-010")
def test_a_child_pairs_nothing_and_revokes_nothing_by_session_or_key(world: World) -> None:
    made = world.create(world.admin, "kid").json()
    key = world.key("kid")
    alone = world.env.other_client("10.0.0.50")
    bearer = {"Authorization": f"Bearer {key}"}
    for client, headers in ((world.kid, {}), (alone, bearer)):
        csrf = {CSRF_HEADER: world.env.csrf(client)} if not headers else {}
        h = {**headers, **csrf}
        assert client.get(TOKENS, headers=h).status_code == 403
        assert client.get(SETUP, headers=h).status_code == 403
        assert client.post(TOKENS, headers=h, json={}).status_code == 403
        assert client.delete(f"{TOKENS}/{made['public_id']}", headers=h).status_code == 403
    assert world.active(made["public_id"])


@pytest.mark.req("ENF-SEC-010")
def test_a_member_lists_and_revokes_only_their_own_tokens(world: World) -> None:
    mine = world.create(world.mum).json()
    theirs = world.create(world.dad).json()
    assert [i["public_id"] for i in world.mum.get(TOKENS).json()["items"]] == [mine["public_id"]]
    # another profile's token answers like one that is not there (IDOR)
    stranger = world.send(world.mum, "DELETE", f"{TOKENS}/{theirs['public_id']}")
    absent = world.send(world.mum, "DELETE", f"{TOKENS}/zzzzzzzz")
    assert stranger.status_code == absent.status_code == 404
    assert stranger.json()["code"] == absent.json()["code"]
    assert world.active(theirs["public_id"])
    done = world.send(world.mum, "DELETE", f"{TOKENS}/{mine['public_id']}")
    assert done.status_code == 204
    assert not world.active(mine["public_id"])
    assert world.send(world.mum, "DELETE", f"{TOKENS}/{mine['public_id']}").status_code == 404


def test_an_admin_lists_and_revokes_everyones_tokens(world: World) -> None:
    mum = world.create(world.mum).json()
    kid = world.create(world.admin, "kid").json()
    listed = world.admin.get(TOKENS).json()["items"]
    assert {i["public_id"] for i in listed} == {mum["public_id"], kid["public_id"]}
    assert all("secret" not in i for i in listed)
    for token in (mum, kid):
        assert (
            world.send(world.admin, "DELETE", f"{TOKENS}/{token['public_id']}").status_code == 204
        )
        assert not world.active(token["public_id"])
    actions = [r[0] for r in db_rows(world.env.settings, "SELECT action FROM audit")]
    assert actions.count("device_token.created") == 2
    assert actions.count("device_token.revoked") == 2


