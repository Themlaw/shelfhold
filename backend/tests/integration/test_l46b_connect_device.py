@pytest.mark.req("ENF-SEC-010")
def test_an_api_key_manages_no_device_token(world: World) -> None:
    made = world.create(world.mum).json()
    for username in ("admin", "mum"):
        key = world.key(username)
        alone = world.env.other_client("10.0.0.60")
        bearer = {"Authorization": f"Bearer {key}"}
        assert alone.get(TOKENS, headers=bearer).status_code in (401, 403)
        assert alone.get(SETUP, headers=bearer).status_code in (401, 403)
        create = alone.post(TOKENS, headers=bearer, json={"subject_user_id": world.ids["mum"]})
        assert create.status_code in (401, 403)
        gone = alone.delete(f"{TOKENS}/{made['public_id']}", headers=bearer)
        assert gone.status_code in (401, 403)
    assert world.active(made["public_id"])
    assert db_rows(world.env.settings, "SELECT COUNT(*) FROM device_token")[0][0] == 1


@pytest.mark.req("ENF-SEC-010", "EF-USR-024")
def test_a_device_token_manages_no_device_token(world: World) -> None:
    made = world.create(world.mum).json()
    import base64

    basic = base64.b64encode(f"{made['public_id']}:{made['secret']}".encode()).decode()
    key = md5(made["secret"])
    ways = (
        {"Authorization": f"Basic {basic}"},
        {"x-auth-user": made["public_id"], "x-auth-key": key},
        {"Authorization": f"Bearer {made['secret']}"},
    )
    for headers in ways:
        alone = world.env.other_client("10.0.0.70")
        assert alone.get(TOKENS, headers=headers).status_code in (401, 403)
        assert alone.post(TOKENS, headers=headers, json={}).status_code in (401, 403)
        gone = alone.delete(f"{TOKENS}/{made['public_id']}", headers=headers)
        assert gone.status_code in (401, 403)
    assert world.active(made["public_id"])


