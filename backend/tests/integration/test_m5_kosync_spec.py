def test_kosync_headers_x_auth_user_x_auth_key_accept(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """The three headers of `KOSyncClient.lua`: `x-auth-user` is the token's public identifier,
    `x-auth-key` the md5 of its secret, and `accept` names the vendor media type."""
    _item, digest = volume(lab)
    headers = kosync(lab.mum.public_id, lab.mum.secret)
    assert headers["accept"] == "application/vnd.koreader.v1+json"
    auth = lab.mum.client.get(AUTH, headers=headers)
    assert auth.status_code == 200 and auth.json() == {"authorized": "OK"}
    body = {
        "document": digest, "progress": "7", "percentage": 7 / 20, "device": "Libra 2",
        "device_id": "A1B2C3",
    }  # fmt: skip
    sent = lab.mum.client.put(PUT, json=body, headers=headers)
    assert sent.status_code == 200
    got = lab.mum.client.get(f"/kosync/syncs/progress/{digest}", headers=headers)
    assert got.status_code == 200 and got.json()["progress"] == "7"
    # the key is the md5 of the token's secret: the secret itself, the account password and its
    # md5 are no key; the identifier is the token's, never the profile's name
    for wrong in (
        kosync(lab.mum.public_id, lab.mum.secret, hashed=False),
        kosync(lab.mum.public_id, PASSWORD),
        kosync(lab.mum.public_id, md5(PASSWORD), hashed=False),
        kosync("mum", lab.mum.secret),
        {"accept": "application/vnd.koreader.v1+json", "x-auth-user": lab.mum.public_id},
        {"accept": "application/vnd.koreader.v1+json", "x-auth-key": md5(lab.mum.secret)},
    ):
        refused = lab.mum.client.get(AUTH, headers=wrong)
        assert refused.status_code == 401, wrong


def test_kosync_four_routes(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """The four routes of `api.json`, and their codes: `users/create` 402, `users/auth` 200 or
    401, `PUT /syncs/progress` 200 `{document, timestamp}`, `GET /syncs/progress/:document` 200
    with the position or `{}`."""
    _item, digest = volume(lab)
    headers = kosync(lab.mum.public_id, lab.mum.secret)
    assert lab.mum.client.post(CREATE, json={}, headers=headers).status_code == 402
    assert lab.mum.client.get(AUTH, headers=headers).status_code == 200
    done = push(lab.mum, digest, "7", 7 / 20)
    assert done.status_code == 200
    assert set(done.json()) == {"document", "timestamp"} and done.json()["document"] == digest
    got = pull(lab.mum, digest)
    assert got.status_code == 200
    assert set(got.json()) == {
        "document", "progress", "percentage", "device", "device_id", "timestamp"
    }  # fmt: skip
    assert got.json()["progress"] == "7"
    # without the token, the two routes that read the profile answer 401
    bare = lab.env.other_client("10.0.0.77")
    body = {"document": digest, "progress": "1", "percentage": 0.05, "device": "d"}
    assert bare.get(AUTH).status_code == 401
    assert bare.put(PUT, json=body).status_code == 401
    assert bare.get(f"/kosync/syncs/progress/{digest}").status_code == 401


def test_kosync_users_create_disabled(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """The accounts are the profiles of Shelfhold: the Register button never creates one,
    whoever asks and whatever it sends, and the message tells the reader why."""
    before = users(lab)
    for headers in ({}, kosync(lab.mum.public_id, lab.mum.secret)):
        for payload in (
            {},
            {"username": "newbie", "password": "0" * 32},
            {"username": "mum", "password": PASSWORD},
        ):
            refused = lab.mum.client.post(CREATE, json=payload, headers=headers)
            assert refused.status_code == 402
            assert "newbie" not in refused.text
    assert users(lab) == before
    asked = lab.mum.client.post(CREATE, json={}, headers={"accept-language": "fr, en"})
    assert "Shelfhold" in asked.json()["message"]  # what the device shows (`doRegister`)


def test_kosync_hash_computed_on_exported_file(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """The digest is of the bytes the e-reader holds: the exported file's. A rewrite changes
    the bytes, the alias follows, and the old digest still finds the book."""
    item, digest = exported(lab)
    assert push(lab.mum, digest, "7", 7 / 20).status_code == 200
    (row,) = positions(lab)
    assert (row.carrier_type, row.carrier_id) == ("export_item", item.item_id)
    assert pull(lab.mum, digest).json()["progress"] == "7"
    # a digest of any other bytes is an unknown document: nothing is stored
    stranger = koreader_partial_md5(io.BytesIO(b"other bytes entirely"))
    assert push(lab.mum, stranger, "3").status_code == 200
    assert len(positions(lab)) == 1
    # the rewrite: new bytes, a new alias line, and the old digest still resolves the book
    lib = library(lab)
    lib.items = [item]
    lib.rewrite(item, Chapter.simple("1", count=25), record=True)
    data = item.path.read_bytes()
    with lab.seed.engine.begin() as connection:
        assert record_export_alias(
            connection, destination_id=None, export_item_id=item.item_id,
            file_hash="sha256:" + hashlib.sha256(data).hexdigest(), path=item.path,
        )  # fmt: skip
    new_digest = koreader_partial_md5(io.BytesIO(data))
    assert new_digest != digest
    assert push(lab.mum, digest, "9", 9 / 25).status_code == 200  # the old hash, the same book
    assert push(lab.mum, new_digest, "9", 9 / 25).status_code == 200
    assert {row.carrier_id for row in positions(lab)} == {item.item_id}


def test_kosync_auth_uses_device_token_secret(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """Passe 11: the « password » of kosync is the secret of a device token, and no equivalent
    of the account password opens the routes or sits in the base."""
    for reader in (lab.mum, lab.kid):
        ok = reader.client.get(AUTH, headers=kosync(reader.public_id, reader.secret))
        assert ok.status_code == 200
    with lab.seed.engine.connect() as connection:
        digest = connection.execute(
            sa.text("SELECT secret_digest FROM device_token WHERE public_id = :p"),
            {"p": lab.mum.public_id.lower()},
        ).scalar_one()
    assert md5(PASSWORD) not in digest and PASSWORD not in digest
    assert digest != hashlib.sha256(md5(PASSWORD).encode()).hexdigest()


def test_kosync_volume_hash_resolves_single_export_item(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """Passe 7 (G9): the digest of a volume of 8 chapters resolves one exported file, without a
    409: the position is anchored on that file alone."""
    item, digest = exported(lab, covers=8, kind="bundle")
    with lab.seed.engine.connect() as connection:
        covered = int(
            connection.execute(
                sa.text("SELECT count(*) FROM unit_coverage WHERE carrier_id = :i"),
                {"i": item.item_id},
            ).scalar_one()
        )
    assert covered == 8  # a volume of 8 chapters, one file
    answer = push(lab.mum, digest, "15", 15 / 20)
    assert answer.status_code == 200  # and never a 409
    rows = positions(lab)
    assert len(rows) == 1
    assert (rows[0].carrier_type, rows[0].carrier_id) == ("export_item", item.item_id)
    assert pull(lab.mum, digest).json()["progress"] == "15"


def test_kosync_ambiguous_hash_never_guesses(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """The same digest on two files the profile may see: neither is picked (a guess would write
    on the wrong file). The answer is the one of an accepted position, and nothing is stored."""
    first, digest = volume(lab)
    other = library(lab).add(Chapter.simple("2", count=20))
    with lab.seed.engine.begin() as connection:
        connection.execute(
            sa.insert(export.document_alias).values(
                export_item_id=other.item_id,
                file_hash="sha256:" + "cd" * 32,
                content_hash="sha256:" + "cd" * 32,
                koreader_partial_md5="md5:" + digest,
            )
        )
    assert first.item_id != other.item_id
    answer = push(lab.mum, digest, "3")
    assert answer.status_code == 200  # a 409 would jam the queue of the device
    assert positions(lab) == []  # nothing on either candidate
    assert (pull(lab.mum, digest).status_code, pull(lab.mum, digest).json()) == (200, {})
    counter = lab.env.app.state.kosync_unknown  # type: ignore[attr-defined]  # what Santé reads
    assert counter.of(lab.mum.public_id, "ambiguous") == 1


def test_kosync_metadata_never_used_to_match(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """The trap of §1: the spec's « repli d'appariement par champ metadata » is refused by
    ADR-0053 (`metadata` is ignored). A title never stands in for a digest, and never overrides
    the file the digest names."""
    item, digest = exported(lab)
    _other_item, other_digest = exported(lab, number="2")
    title = lab.seed.title_of("ok")
    # an unknown digest with the metadata of a known book: no fallback, nothing stored
    answer = push(
        lab.mum, ABSENT_MD5, "5",
        metadata={"title": title, "authors": ["Author"], "language": "en", "series": "Series"},
    )  # fmt: skip
    assert answer.status_code == 200
    assert positions(lab) == []
    assert pull(lab.mum, ABSENT_MD5).json() == {}
    # a known digest with the metadata of another book: the digest decides, the metadata does
    # not move the position to the other file
    mislabeled = push(
        lab.mum, digest, "5", metadata={"title": "Another Tale", "authors": ["Somebody Else"]},
    )  # fmt: skip
    assert mislabeled.status_code == 200
    rows = positions(lab)
    assert len(rows) == 1 and rows[0].carrier_id == item.item_id
    assert pull(lab.mum, other_digest).json() == {}


def test_kosync_get_unresolved_returns_empty_object(lab: World) -> None:  # noqa: F811 (the fixture of the suite)
    """Whatever does not resolve — an unknown digest, one the profile may not see, a string that
    is no digest — is 200 and `{}`: the answer KOReader shows as « no progress »."""
    _hidden, hidden_digest = volume(lab, key="above")
    for reader, document in (
        (lab.mum, ABSENT_MD5),
        (lab.kid, hidden_digest),  # above the child's ceiling: as an unknown one
        (lab.mum, "notadigest"),
        (lab.mum, "0" * 32),
    ):
        got = pull(reader, document)
        assert (got.status_code, got.json()) == (200, {}), document
    # the control: the same digest resolves and answers for the adult
    assert push(lab.mum, hidden_digest, "3").status_code == 200
    assert pull(lab.mum, hidden_digest).json()["progress"] == "3"
    assert pull(lab.kid, hidden_digest).json() == {}
    assert {row.user_id for row in positions(lab)} == {positions_user(lab, "mum")}
