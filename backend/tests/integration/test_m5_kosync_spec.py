"""M5 L08: the names of the spec (03, EF-LEC-009) on the behaviour the M4 lots delivered (L47,
L50, ADR-0053 §4 and §5).

The spec's words, read against the code that exists: the three headers of `KOSyncClient.lua`,
the four routes of `api.json`, `users/create` closed, the digest computed on the bytes of the
exported file, the key that is the md5 of a device token's secret and never of an account
password, a volume's digest that resolves one exported file, an ambiguous digest that is never
guessed, a `metadata` field that is never used to match (the trap of §1 of the requirement: the
fallback by title is refused by ADR-0053, `metadata` is ignored), and a GET that resolves nothing
and answers `{}`. Real requests on the test application, tokens generated by the fixtures, no
network out.
"""

