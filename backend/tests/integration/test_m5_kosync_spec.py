AUTH = "/kosync/users/auth"
CREATE = "/kosync/users/create"


def exported(
    world: World,
    key: str = "ok",
    *,
    number: str = "1",
    count: int = 20,
    covers: int = 1,
    kind: str = "unit",
) -> tuple[Exported, str]:
    """A file the export placed, aliased by the export's own code (never by the test), and the
    digest KOReader computes on its bytes."""
    item = library(world, key).add(Chapter.simple(number, count=count), kind=kind, covers=covers)
    data = item.path.read_bytes()
    with world.seed.engine.begin() as connection:
        assert record_export_alias(
            connection, destination_id=None, export_item_id=item.item_id,
            file_hash="sha256:" + hashlib.sha256(data).hexdigest(), path=item.path,
        )  # fmt: skip
    return item, koreader_partial_md5(io.BytesIO(data))


def users(world: World) -> int:
    with world.seed.engine.connect() as connection:
        return int(connection.execute(sa.text("SELECT count(*) FROM user")).scalar_one())


